"""Freeze parameterized authored development inputs; never run a benchmark.

Scenario and expected-decision labels are written only to the external manifest.
Profile identifiers, graph identifiers and edge identifiers are neutral.
"""
from __future__ import annotations

import argparse
from copy import deepcopy
import hashlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
FAMILIES = ("argument_product", "layered_reconvergence", "correlated_frames",
            "horizon_boundary", "off_goal_load")
SOURCES = ("__init__.py", "manifest.py", "oracle.py", "refinement.py", "refinement_oracle.py")
CLOCK = 100
PATH_PRODUCT_LIMIT = 4096
CASE_LIMIT = 512
SOURCE_REF = "Authored finite relation generated by generate_refinement_scaling_v1.py; no source-to-model fidelity claim"


def _axis(values, name, minimum, maximum):
    if not values or any(type(value) is not int or not minimum <= value <= maximum for value in values):
        raise ValueError(f"{name} must contain integers in [{minimum}, {maximum}]")
    if len(set(values)) != len(values):
        raise ValueError(name + " contains duplicates")
    return tuple(sorted(values))


def configuration(widths=(2,), depths=(2,), argument_counts=(2,), budgets=(32, 256, 4096, 100000), families=FAMILIES):
    widths = _axis(widths, "widths", 2, 16)
    depths = _axis(depths, "depths", 1, 8)
    argument_counts = _axis(argument_counts, "argument_counts", 1, 8)
    budgets = _axis(budgets, "budgets", 1, 10000000)
    if not families or len(set(families)) != len(families) or any(value not in FAMILIES for value in families):
        raise ValueError("Unknown or duplicate family")
    if max(widths) ** max(depths) > PATH_PRODUCT_LIMIT:
        raise ValueError("Declared layered path product exceeds the 4096-case-work preparation bound")
    if max(widths) ** max(argument_counts) > PATH_PRODUCT_LIMIT:
        raise ValueError("Declared argument product exceeds the 4096-assignment preparation bound")
    return {"widths": list(widths), "depths": list(depths), "argument_counts": list(argument_counts),
            "budgets": list(budgets), "families": [name for name in FAMILIES if name in families],
            "evaluation_clock": CLOCK}


def _profile(states, horizon, goal=None):
    goal = states - 1 if goal is None else goal
    return {"schema_version": "recipe-continuation/1", "id": "unassigned",
            "model": {"schema_version": "finite-continuation/1", "id": "unassigned",
                "route": "Authored finite development graph; not a qualified protocol route",
                "provenance": {"kind": "authored-development", "source": "scripts/generate_refinement_scaling_v1.py",
                    "review_status": "AI-authored parameterized development; human review pending"},
                "horizon": horizon, "evidence": {"complete": True, "observed_at": 0, "valid_until": 4102444800},
                "initial": "s000", "states": {f"s{i:03d}": {"safe": True, "done": i == goal} for i in range(states)},
                "transitions": [], "runtime_contract": {"goal": [{"field": "done", "op": "eq", "value": True}],
                    "invariants": [{"field": "safe", "op": "eq", "value": True}]}},
            "initial_bindings": {}, "relations": {}, "coverage": {"complete": True,
                "scope": "Only declared finite graph, horizon, literal/binding alternatives and supplied relations"}}


def _relation(arguments=None, emit=None, guards=None, updates=None):
    return {"source_ref": SOURCE_REF, "arguments": {} if arguments is None else arguments,
            "emit": {"object": {}} if emit is None else emit,
            "guards": [] if guards is None else guards, "updates": {} if updates is None else updates}


def _edge(profile, source, target, relation=None):
    identifier = f"e{len(profile['model']['transitions']):04d}"
    profile["model"]["transitions"].append({"id": identifier, "source": f"s{source:03d}",
                                           "target": f"s{target:03d}", "operation": "declared_recipe"})
    profile["relations"][identifier] = _relation() if relation is None else deepcopy(relation)


def _false_guard():
    return {"op": "eq", "left": {"const": 0}, "right": {"const": 1}}


def _arguments(width, count):
    return {f"a{i:03d}": [{"literal": value} for value in range(width)] for i in range(count)}


def argument_product(width, count, scenario):
    profile = _profile(2, 1)
    arguments = _arguments(width, count)
    target = 0 if scenario == "first_witness" else width - 1
    guards = [{"op": "eq", "left": {"arg": name}, "right": {"const": target}} for name in arguments]
    if scenario == "refutation":
        guards[-1]["right"] = {"const": width}
    emit = {"object": {name: {"arg": name} for name in arguments}}
    if scenario == "opaque":
        emit, guards = {"unknown": "request_bytes"}, []
    _edge(profile, 0, 1, _relation(arguments, emit, guards))
    return profile


def layered_reconvergence(width, depth, scenario):
    profile = _profile(depth + 1, depth)
    for level in range(depth):
        relation = _relation()
        if ((scenario == "early_refutation" and level == 0)
                or (scenario == "late_refutation" and level == depth - 1)):
            relation["guards"] = [_false_guard()]
        if scenario == "opaque" and level == depth - 1:
            relation["emit"] = {"unknown": "request_bytes"}
        for _ in range(width):
            _edge(profile, level, level + 1, relation)
    return profile


def correlated_frames(width, depth, scenario):
    # At least two steps are needed to create then read a correlated frame.
    depth = max(2, depth)
    profile = _profile(depth + 1, depth)
    for value in range(width):
        # Padded values keep frame sort order aligned with edge/recipe order,
        # including widths above ten, for both independently written solvers.
        token = f"v{value:04d}"
        _edge(profile, 0, 1, _relation(updates={"x": {"const": token}, "y": {"const": token}}))
    for level in range(1, depth - 1):
        _edge(profile, level, level + 1)
    target = 0 if scenario in ("first_witness", "unmatched_pair") else width - 1
    target_y = (target + 1) % width if scenario == "unmatched_pair" else target
    arguments = {name: [{"binding": name}] for name in ("x", "y")}
    guards = [{"op": "eq", "left": {"arg": name}, "right": {"const": f"v{value:04d}"}}
              for name, value in (("x", target), ("y", target_y))]
    emit = {"object": {name: {"arg": name} for name in arguments}}
    if scenario == "opaque":
        emit, guards = {"unknown": "request_bytes"}, []
    _edge(profile, depth - 1, depth, _relation(arguments, emit, guards))
    return profile


def horizon_boundary(depth, slack):
    profile = _profile(depth + 1, depth + slack)
    for level in range(depth):
        _edge(profile, level, level + 1)
    return profile


def off_goal_load(width, count, scenario):
    profile = _profile(width + 2, 1, goal=1)
    args = _arguments(width, count)
    emit = ({"unknown": "request_bytes"} if scenario == "irrelevant_opaque"
            else {"object": {name: {"arg": name} for name in args}})
    for index in range(width):
        _edge(profile, 0, index + 2, _relation(args, emit))
    _edge(profile, 0, 1, _relation(guards=[] if scenario == "witness" else [_false_guard()]))
    return profile


def build_cases(config):
    """Generate profiles and separate authored semantic expectations."""
    cases = []

    def add(family, scenario, parameters, profile, expected, rationale):
        number = len(cases) + 1
        profile["id"], profile["model"]["id"] = f"scale-{number:04d}", f"graph-{number:04d}"
        cases.append({"family": family, "scenario": scenario, "parameters": parameters,
                      "expected_decision_with_sufficient_budget": expected,
                      "expectation_rationale": rationale, "profile": profile})

    for family in config["families"]:
        if family == "argument_product":
            for width in config["widths"]:
                for count in config["argument_counts"]:
                    for scenario in ("first_witness", "last_witness", "refutation", "opaque"):
                        expected = "unknown" if scenario == "opaque" else "unsupported" if scenario == "refutation" else "supported"
                        add(family, scenario, {"choices_per_argument": width, "arguments": count,
                            "assignment_product": width ** count}, argument_product(width, count, scenario), expected,
                            "Finite Cartesian recipes: a permitted endpoint tuple witnesses; an out-of-domain guard refutes; opaque emission abstains.")
        elif family == "layered_reconvergence":
            for width in config["widths"]:
                for depth in config["depths"]:
                    for scenario in ("witness", "early_refutation", "late_refutation", "opaque"):
                        expected = "supported" if scenario == "witness" else "unknown" if scenario == "opaque" else "unsupported"
                        add(family, scenario, {"width": width, "depth": depth, "abstract_paths": width ** depth},
                            layered_reconvergence(width, depth, scenario), expected,
                            "Parallel edges reconverge without frame changes: an explicit false layer blocks every full path; an opaque final layer abstains.")
        elif family == "correlated_frames":
            for width in config["widths"]:
                for depth in sorted({max(2, value) for value in config["depths"]}):
                    for scenario in ("first_witness", "last_witness", "unmatched_pair", "opaque"):
                        expected = "unsupported" if scenario == "unmatched_pair" else "unknown" if scenario == "opaque" else "supported"
                        add(family, scenario, {"frames": width, "depth": depth}, correlated_frames(width, depth, scenario), expected,
                            "Only whole frames (x=i,y=i) are generated; matching marginals from different frames cannot form one witness.")
        elif family == "horizon_boundary":
            for depth in config["depths"]:
                for slack in (-1, 0, 1):
                    add(family, f"slack_{slack}", {"chain_length": depth, "horizon": depth + slack},
                        horizon_boundary(depth, slack), "unsupported" if slack < 0 else "supported",
                        "The sole goal is at chain_length steps; a shorter complete horizon refutes only bounded completion.")
        else:
            for width in config["widths"]:
                for count in config["argument_counts"]:
                    for scenario in ("witness", "refutation", "irrelevant_opaque"):
                        add(family, scenario, {"dead_branches": width, "choices_per_argument": width, "arguments": count,
                            "off_goal_assignments": width ** (count + 1)}, off_goal_load(width, count, scenario),
                            "supported" if scenario == "witness" else "unsupported",
                            "Dead branches cannot reach a goal in the horizon; their relation uncertainty cannot establish or obstruct the separate goal edge.")
    if len(cases) > CASE_LIMIT:
        raise ValueError("Too many generated cases; split the declared matrix into smaller allocations")
    return cases


def record(path, root):
    raw = path.read_bytes()
    return {"path": path.relative_to(root).as_posix(), "bytes": len(raw), "sha256": hashlib.sha256(raw).hexdigest()}


def write_json(path, value):
    with path.open("x", encoding="utf-8", newline="\n") as handle:
        json.dump(value, handle, indent=2, ensure_ascii=False, allow_nan=False)
        handle.write("\n")


def generate(output, config):
    config = configuration(**{name: config[name] for name in ("widths", "depths", "argument_counts", "budgets", "families")})
    cases = build_cases(config)
    sys.dont_write_bytecode = True
    sys.path.insert(0, str(ROOT / "src"))
    from interoperability import refinement, refinement_oracle
    for case in cases:
        refinement.validate(case["profile"])
        refinement_oracle.validate_profile(case["profile"])
    output = Path(output).absolute()
    if ".." in output.parts or any(path.is_symlink() for path in (output, *output.parents)):
        raise ValueError("Output traversal/symlink is not allowed")
    output.mkdir(parents=True, exist_ok=False)
    (output / "profiles").mkdir()
    (output / "source").mkdir()
    originals = [Path(__file__).resolve(), *(ROOT / "src/interoperability" / name for name in SOURCES)]
    source_before = {str(path): hashlib.sha256(path.read_bytes()).hexdigest() for path in originals}
    for path in originals:
        target = output / "source" / path.name
        with target.open("xb") as handle:
            handle.write(path.read_bytes())
    suite = {"schema_version": "admission-benchmark-suite/1", "id": "recipe-scaling-development-v1",
             "split": "development", "evaluation_clock": CLOCK, "cases": []}
    labels = []
    for case in cases:
        profile = case["profile"]
        path = output / "profiles" / (profile["id"] + ".json")
        write_json(path, profile)
        row = record(path, output)
        suite["cases"].append({"path": row["path"], "family": case["family"]})
        labels.append({key: value for key, value in case.items() if key != "profile"} | {
            "profile_id": profile["id"], "input": row, "states": len(profile["model"]["states"]),
            "edges": len(profile["model"]["transitions"]), "horizon": profile["model"]["horizon"]})
    write_json(output / "suite.json", suite)
    source_after = {str(path): hashlib.sha256(path.read_bytes()).hexdigest() for path in originals}
    if source_before != source_after:
        raise ValueError("Generator/validator source changed; preserve this failed allocation")
    rows = sorted((record(path, output) for path in output.rglob("*") if path.is_file()), key=lambda row: row["path"])
    manifest = {"schema_version": "recipe-scaling-development-manifest/1", "status": "frozen_not_benchmarked",
        "configuration": config, "cases": labels, "files": rows,
        "inventory_scope": "Every generated regular file except this manifest itself",
        "solver_inputs": "Individual profiles only; suite families, scenarios and expectations are external labels",
        "expected_decisions": "Authored finite semantic expectations with sufficient budget; budget-exhausted unknown is not a semantic error",
        "comparison": {"candidate": "interoperability.refinement:evaluate", "direct": "interoperability.refinement_oracle:evaluate",
            "same_input_clock_and_budget": True, "reference_implementation_is_baseline": True,
            "work_units_are_identical_primitives": False,
            "report": ["decision", "reason", "certificate validity and checking cost", "all invocation timings",
                       "relation_checks or argument_assignments", "expression_evaluations", "refinements",
                       "abstract_paths", "product_states", "cached_relation_outcomes", "peak_frames"]},
        "development_only": True, "held_out": False, "novelty_established": False, "qualified_domains": 0,
        "independent_templates_claimed": False, "measurements_executed_by_generator": 0,
        "generator_and_validator_sources_unchanged": True,
        "limits": {"maximum_argument_or_layered_path_product": PATH_PRODUCT_LIMIT, "maximum_cases": CASE_LIMIT},
        "limitations": "Related parameterized authored variants, not application gold or held-out evidence. No timing, winner or scalability claim is established by generation."}
    write_json(output / "manifest.json", manifest)
    return {"status": manifest["status"], "cases": len(cases), "families": config["families"],
            "output": str(output), "manifest": record(output / "manifest.json", output)}


def integers(value):
    try:
        return tuple(int(item) for item in value.split(","))
    except ValueError as error:
        raise argparse.ArgumentTypeError("Expected comma-separated integers") from error


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", required=True, type=Path)
    parser.add_argument("--widths", type=integers, default=(2,))
    parser.add_argument("--depths", type=integers, default=(2,))
    parser.add_argument("--argument-counts", type=integers, default=(2,))
    parser.add_argument("--budgets", type=integers, default=(32, 256, 4096, 100000))
    parser.add_argument("--families", default=",".join(FAMILIES))
    args = parser.parse_args()
    config = configuration(args.widths, args.depths, args.argument_counts, args.budgets, args.families.split(","))
    print(json.dumps(generate(args.output, config), indent=2))


if __name__ == "__main__":
    main()
